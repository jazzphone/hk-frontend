// A big file that was cut into parts is still ONE source to these suites. A shell lists its parts in `var PARTS = [...]`, the
// files of the folder named by the loader beside it ('/hk/<folder>/' + file): hk-detail.js (the files of frontend/sheets/, the
// panels one per kind of device and the helpers they share), hk-grid-cards.js, ... every file tools/split_js.py cut up.
//
// The suites were written when each was one file, and what each pins is the code as a whole, so this makes the shell's
// name mean that:
//
//   load('.../frontend/<dir>/<shell>.js')         loads the part files first (each registers a function the shell runs as
//                                                 it loads, as a browser's import() would leave it), then the shell
//   read/readFile('.../frontend/<dir>/<shell>.js')   answers the shell's text followed by every part file's
//   readRunnable('.../frontend/<dir>/<shell>.js')    the text to EVAL when a suite edits the shell before running it (a
//                                                    stand-in for a variable, say): every part's text first, then the
//                                                    shell's, so the shell finds its parts registered and starts at once
//
// Any other path is untouched. A shell is found by its text (the list and the loader's address), so a file split later
// needs no change in this one. A file that IS a shell but whose list or loader address is gone is an error here, never "a file
// that is not cut into parts" (the parts would silently drop out of every load and read): a shell is any
// file that carries the generated loader's banner. Loaded by tests/run into the prelude, after HK_ROOT. Not a suite.
(function () {
  'use strict';
  var realLoad = load, realRead = readFile, realReadShort = read, found = {};
  var LIST = /var PARTS = \[([^\]]*)\]/, FOLDER = /'\/hk\/([\w-]+)\/' \+ file/,
      BANNER = '(generated by tools/split_js.py)';
  // the part files of a shell (their paths), or null when the path is not a shell; kept per path
  function parts(p) {
    if (typeof p !== 'string' || p.slice(-3) !== '.js' || p.lastIndexOf('/frontend/') < 0) return null;
    if (found[p] !== undefined) return found[p];
    var out = null, text;
    try { text = realRead(p); } catch (e) { text = ''; }
    var list = LIST.exec(text), folder = FOLDER.exec(text);
    if (list && folder) {
      var root = p.slice(0, p.lastIndexOf('/frontend/'));
      out = (list[1].match(/'[^']+'/g) || []).map(function (q) { return root + '/frontend/' + folder[1] + '/' + q.slice(1, -1); });
    } else if (text && (p.slice(p.lastIndexOf('/') + 1) === 'hk-detail.js' || text.indexOf(BANNER) >= 0)) {
      throw new Error(p + ' is a shell (hk-detail.js, or it has the generated loader) but its parts list is not there: ' +
                      '`var PARTS = [...]` and the loader\'s \'/hk/<folder>/\' + file');
    }
    found[p] = out;
    return out;
  }
  globalThis.load = function (p) {
    var files = parts(p);
    if (files) files.forEach(function (f) { realLoad(f); });
    return realLoad.apply(this, arguments);
  };
  function text(reader) {
    return function (p) {
      var shell = reader.apply(this, arguments), files = parts(p);
      if (!files || typeof shell !== 'string') return shell;
      return shell + '\n' + files.map(function (f) { return reader(f); }).join('\n');
    };
  }
  globalThis.readRunnable = function (p) {
    var files = parts(p);
    return (files ? files.map(function (f) { return realRead(f); }).join('\n') + '\n' : '') + realRead(p);
  };
  // readPyPackage(dir): a Python package that was one module (hk_core/settings/model/, from model.py: tools/split_py.py) as one
  // text, as the suites read the module: __init__.py, then each file it imports from, in its order
  globalThis.readPyPackage = function (dir) {
    var init = realRead(dir + '/__init__.py'), seen = {}, out = [init];
    (init.match(/^from \.(\w+) import/gm) || []).forEach(function (line) {
      var name = /\.(\w+)/.exec(line)[1];
      if (!seen[name]) { seen[name] = true; out.push(realRead(dir + '/' + name + '.py')); }
    });
    return out.join('\n');
  };
  globalThis.readFile = text(realRead);
  globalThis.read = text(realReadShort);
  // cut(src, a, b): src from `a` up to `b`, as a suite cut a class out of one file (`class X` to `register('x'`). In a shell
  // and its parts read as one text the end may be in the shell, which comes first: then the cut ends where the file that
  // holds `a` ends (a part's last line `})();`), so the class is read whole from the part it moved to (phase 24).
  globalThis.cut = function (src, a, b) {
    var i = src.indexOf(a), j = src.indexOf(b, i);
    if (i < 0) return '';
    if (j < 0 || src.lastIndexOf(b, i) >= 0 && src.indexOf('\n})();\n', i) < j) j = src.indexOf('\n})();\n', i);
    return src.slice(i, j < 0 ? src.length : j);
  };
})();
