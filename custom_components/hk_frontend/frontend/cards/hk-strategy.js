      var own = ownRecent();
      if (own ? (window.hkPopupCover || 0) > 0 || editing() : busy()) { built.timer = setTimeout(due, own ? MINE_POLL : 5000); return; }
      built.sig = inputs(built.seg);
      built.mine = 0;
