      colourName = K.colourName; covering = K.covering; dashNow = K.dashNow; DAY = K.DAY; dayRows = K.dayRows;
      deepActive = K.deepActive; def = K.def; defaultFavourites = K.defaultFavourites; disabled = K.disabled;
      domainOf = K.domainOf; downsample = K.downsample; dur = K.dur; esc = K.esc; fanGuard = K.fanGuard;
      fanLabel = K.fanLabel; fanSteps = K.fanSteps; favMatches = K.favMatches; focusables = K.focusables;
      fromDashboard = K.fromDashboard; GENERIC_SKIP = K.GENERIC_SKIP; genericControl = K.genericControl;
      genericRows = K.genericRows; glyph = K.glyph; glyphSearch = K.glyphSearch; glyphsFor = K.glyphsFor;
      goFor = K.goFor; haRoot = K.haRoot; headIcon = K.headIcon; isOn = K.isOn; kelvinRgb = K.kelvinRgb;
      kindOf = K.kindOf; lightCaps = K.lightCaps; lightFill = K.lightFill; lookFor = K.lookFor; lookOf = K.lookOf;
