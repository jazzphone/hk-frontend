// hk-media.js -- the music cards: the player, the screensaver's now-playing line, the speaker picker
//
// hk-now-playing-card (THE player), hk-screensaver-now-card,
// hk-speaker-picker-card, and hk-browse-card (Music Assistant's own web player
// in a frame).
//
// Shared pieces -- HkBase, the editor helpers, register(), create(), the
// snapshot cache -- come from hk-base.js through window.hkCards.
// @ts-check
(function () {
  'use strict';

  // hk-base.js is a Lovelace resource fetched in PARALLEL with this one, so
  // wait for its ready EVENT (never poll: rAF does not fire in a hidden tab,
  // and a tablet behind the screensaver would define nothing -- see
  // hk-base.js).
  function whenBase(fn) {
    if (window.hkCards && window.hkCards.register) return fn(window.hkCards);
    window.addEventListener('hk-cards-ready', function () {
      if (window.hkCards && window.hkCards.register) fn(window.hkCards);
      else console.error('[hk-media] hk-cards-ready fired without hk-base.js');
    }, { once: true });
  }

  // ------------------------------------------------------------ the parts (generated by tools/split_js.py)
  // THIS FILE IS THE SHELL. Its members are cut into the files of web/hk/media/ (the PARTS below, in the order they
  // run) by tools/split_js.py from tools/split_manifests/media.json; `split_js.py --find <name>` says which file holds
  // one. Each file registers one function in window.hkMediaParts; they run here, in this order (a later one may use
  // an earlier one), each given the kit K: what the parts use of the shell, in one object. What the shell uses of them,
  // they hand back on K, and it is taken from there. The files are fetched in parallel; a host that has already loaded
  // them (the suites) starts at once, in the same turn.
  var PARTS = ['hk-media-now.js', 'hk-media-speakers.js', 'hk-media-saver.js', 'hk-media-recent.js', 'hk-media-tv.js'];
  var PARTS_TRIES = 6;
  function partKey(file) { return file.replace(/\.js$/, ''); }
  // ONE FILE THAT DIDN'T COME (a tablet's Wi-Fi waking, the server restarting) used to leave the cards dead until a reload
  // (the third audit pass, WEB-11): the ones still missing are asked for again, a little later each time, at an address
  // of their own -- a browser keeps a failed module's answer for its address
  function loadParts(then, n) {
    // (the first call has no n; the retries and the finish pass it) a shell evaluated twice before its parts arrive
    // must not run them twice: the flag is set at once, not when the parts have run
    if (n === undefined) {
      var started = window.__hkSplitStarted = window.__hkSplitStarted || {};
      if (started['hk-media']) return;
      started['hk-media'] = true;
    }
    n = n || 0;
    var have = window.hkMediaParts || {};
    var missing = PARTS.filter(function (file) { return !have[partKey(file)]; });
    if (!missing.length) {
      try { then(); } catch (err) { console.error('[hk-media] the parts did not start', err); }
      // (the checks that drive a page wait for every shell that started to say it is done)
      (window.__hkSplitDone = window.__hkSplitDone || {})['hk-media'] = true;
      return;
    }
    // (window.hkV: the build's ?v= on an address put together here, web/shim/base.js)
    Promise.all(missing.map(function (file) {
      var u = '/hk/media/' + file, href = window.hkV ? window.hkV(u) : u;
      var got = n ? import(href + (href.indexOf('?') < 0 ? '?' : '&') + 'retry=' + n) : import(href);
      return got.catch(function (err) { return err; });
    })).then(function (got) {
      var err = got.filter(function (r) { return r instanceof Error; })[0];
      var left = PARTS.filter(function (file) { return !(window.hkMediaParts || {})[partKey(file)]; });
      if (!left.length) { loadParts(then, n); return; }
      err = err || new Error(left[0] + ' ran without registering');
      if (n + 1 >= PARTS_TRIES) { console.error('[hk-media] the parts did not start', err); return; }
      console.warn('[hk-media] a part did not load (' + err.message + '); again shortly');
      setTimeout(function () { loadParts(then, n + 1); }, Math.min(1000 * Math.pow(2, n), 15000));
    });
  }
  // ------------------------------------------------------------ end of the parts loader

  whenBase(function (C) {
  if (window.hkMedia) return;                  // double-load guard
  var HkBase = C.HkBase, M = C.M, register = C.register, create = C.create,
      SELECTED_BG = C.SELECTED_BG, SELECTED_TEXT = C.SELECTED_TEXT,
      esc = C.esc, button = C.button;

  // A NESTED CARD'S CLIENT, once the card can take it. hkCards.create configures a card
  // as soon as its element is defined and hands it nothing before; the host adapter's
  // bridge then decides what the child gets (in HA, an HA-drawn card needs the
  // frontend's object). A card that is not defined yet is skipped: the next push feeds it.
  // slice 9: hkCards.create's hkSetClient should take a client, and this goes.
  function feed(el, client) {
    if (el && client && typeof el.setConfig === 'function') window.hkHostClient.bridge(el, client);
  }

  // MUSIC NOT ADDED (2026-10-12). Without the Music feature the player and
  // the speaker picker have no speakers -- empty rooms, "Pick speakers on
  // Play Music" -- so they say what is missing instead. ONLY ON THE
  // INTEGRATION'S OWN ANSWERS: hkMusic.configured() is false until
  // hk_music/subscribe answers, and the settings feed's `added` is a stored
  // copy until it is live, so a house WITH Music never sees this line while
  // a page loads. (Same rule in hk-music.js and hk-library.js.)
  // (a place in Home Assistant's settings, as the host says it: hk-host-shell.js haPlace)
  function NO_MUSIC() { return 'Add the Music feature to play music here (' + window.hkShell.haPlace('Settings → Devices & services → HK Frontend → Add feature') + ').'; }
  function musicMissing() {
    var Mu = window.hkMusic, HS = window.hkSettings;
    if (!Mu || !Mu.configured || Mu.configured()) return false;
    return !!(HS && HS.live && !(C.added && C.added('music')));
  }
  // The line, in place of the card. `_built` goes false, so the card builds
  // itself from scratch once Music is added.
  function drawNoMusic(card) {
    card._root.innerHTML = '';
    var el = document.createElement('hk-plate');
    el.setAttribute('data-hk-role', 'no-music');
    el.style.cssText = 'display:block;padding:24px;box-sizing:border-box;border-radius:' + M.radius + ';' +
      M.glass + ';border:' + M.border + ';text-align:center;font-size:15px;line-height:1.4;' +
      'color:' + window.hkCards.v('ink-2') + '';
    el.textContent = NO_MUSIC();
    card._root.appendChild(el);
    card._built = false;
  }

  var HkBrowseCard, HkMusicPlaylistsCard, HkNowPlayingCard, HkRecentMusicCard, HkScreensaverNowCard,
      HkSpeakerPickerCard, HkTvChannelsCard, playlistTiles, RECENT, recentCovers, tintOf, TV_SLOTS, tvGrid;
  function kit() {
    return {
      button: button, C: C, create: create, drawNoMusic: drawNoMusic, esc: esc, feed: feed, HkBase: HkBase, M: M,
      musicMissing: musicMissing, SELECTED_BG: SELECTED_BG, SELECTED_TEXT: SELECTED_TEXT
    };
  }
  function runParts() {
    var K = kit();
    PARTS.forEach(function (file) { window.hkMediaParts[partKey(file)](K); });
    HkBrowseCard = K.HkBrowseCard; HkMusicPlaylistsCard = K.HkMusicPlaylistsCard;
    HkNowPlayingCard = K.HkNowPlayingCard; HkRecentMusicCard = K.HkRecentMusicCard;
    HkScreensaverNowCard = K.HkScreensaverNowCard; HkSpeakerPickerCard = K.HkSpeakerPickerCard;
    HkTvChannelsCard = K.HkTvChannelsCard; playlistTiles = K.playlistTiles; RECENT = K.RECENT;
    recentCovers = K.recentCovers; tintOf = K.tintOf; TV_SLOTS = K.TV_SLOTS; tvGrid = K.tvGrid;
  }

  loadParts(function () {
    runParts();

    // Listed in the card picker, with an editor, so it can be placed without
    // hand-written YAML.
    register('hk-speaker-picker-card', HkSpeakerPickerCard, 'HK Speaker Picker',
      'Choose one or more speakers, then tap a playlist to play it on them. The speakers, presets and playlists are set up in HK Settings → Pages → Music.',
      C && [
        { name: 'browse_url', label: 'Browse page',
          helper: 'Where the Browse Music pill goes, e.g. ./music-browse on ' + window.hkShell.productName() + '\'s own screens. Empty: no pill. Speakers, presets and playlists are set up in HK Settings → Pages → Music.',
          selector: { text: {} } }
      ],
      // NO browse_url IN THE STUB: ./music-browse is a page only HK Frontend's
      // generated screens have, so on a dashboard of your own the pill would
      // lead nowhere. Without it there is no pill; the option stays.
      function () { return {}; });

    register('hk-now-playing-card', HkNowPlayingCard, 'HK Now Playing',
      'Artwork, track and controls for the music this screen is showing.',
      C && [
        { name: 'hide_idle', label: 'Hide When Idle',
          helper: 'Draws nothing while nothing is playing or paused.',
          selector: { boolean: {} } },
        { name: 'tall', label: 'Tall layout',
          helper: 'Stacks artwork, track and controls in one column, for a narrow column or a phone.',
          selector: { boolean: {} } },
        C.section('Controls', [
          { name: 'meta_card', label: 'Controls Card',
            helper: 'Drawn under the track, as YAML: usually HK Media Controls following the screen\'s music, with the progress bar and volume (just the volume in the tall layout).',
            selector: { object: {} } },
          { name: 'sub_card', label: 'Progress Card',
            helper: 'Tall layout only: drawn between the track and the buttons, as YAML. Usually HK Media Controls with just the progress bar.',
            selector: { object: {} } }
        ], 'mdi:play-pause')
      ],
      // A CARD FROM THE PICKER HAS CONTROLS: the progress bar and volume, as an
      // HK Media Controls card following the screen's music -- what the Play
      // Music page and the docked bar draw (hk-strategy.js mediaBar), in the one
      // slot the default (wide) layout has. `sub_card` has no place in the wide
      // grid (it is the tall layout's and the bar's), so the stub does not use
      // it. No `music: true`: the player always follows the screen's music
      // (hkMusic) and never read it.
      function () {
        return { meta_card: { type: 'custom:hk-media-control-card', color: 'purple', bare: true,
                              parts: ['progress', 'volume'], entity_from: { music: true } } };
      });

    register('hk-screensaver-now-card', HkScreensaverNowCard,
      'HK Screensaver Now Playing',
      'Shows the track playing on any of the listed speakers, for a screensaver.',
      C && [{ name: 'music', label: 'The integration\'s speakers',
              helper: 'Follow the speakers set up for Music, presets first.',
              selector: { boolean: {} } },
            { name: 'players', helper: 'Instead of the above: these players, in priority order (groups first).',
              selector: { entity: { multiple: true, filter: { domain: 'media_player' } } } }],
      function () { return { music: true }; });
    // the screensaver's own (hk-saver.js): not offered in the card picker
    if (C && C.unlisted) C.unlisted('hk-screensaver-now-card');

    register('hk-browse-card', HkBrowseCard, 'HK Browse Music',
      'Music Assistant\'s web player, framed inside a dashboard page.',
      C && [
        { name: 'port', selector: { number: { min: 1, max: 65535, mode: 'box' } } },
        { name: 'path', selector: { text: {} } },
        { name: 'height', selector: { text: {} } }
      ],
      function () { return { port: 8095, path: '/#/home' }; });
    // A PLAYLIST ON THIS SCREEN'S SPEAKERS, as the Music page plays one (hk-music.js _playPlaylist): the rooms of what
    // this screen follows -- a preset's own, else the one -- and hk_frontend.music_play; a failure is said
    HkRecentMusicCard.prototype._playList = function (it, el) {
      var Mu = window.hkMusic, self = this, p = this._target();
      var pre = p && Mu.presets().filter(function (x) { return x.entity === p; })[0];
      var rooms = pre ? pre.members.slice() : p ? [p] : [];
      if (!rooms.length) { window.hkShell.toast({ message: 'Pick a speaker on the Music page to play ' + it.name + '.' }, this); return Promise.resolve(false); }
      if (el.classList.contains('busy')) return Promise.resolve(false);
      el.classList.add('busy');
      // (answers whether it played: the playlists' sheet closes on it)
      return this._callResp('hk_frontend', 'music_play', { rooms: rooms, playlist: it.playlist }).then(function (res) {
        el.classList.remove('busy');
        var r = (res && res.response) || {};
        if (!res.ok || r.ok === false) { window.hkShell.toast({ message: 'Could not play ' + it.name + (r.message ? ': ' + r.message : '') }, self); return false; }
        if (r.leader && Mu.known(r.leader)) Mu.setFocus(r.leader, { hold: true });
        return true;
      });
    };
    // ONE OF A PLAYLIST'S CHOICES, picked in the Music page's sheet (hk-music.js _play: hkCards.chooseSheet), then
    // played as any playlist tile plays
    HkRecentMusicCard.prototype._choose = function (it, el) {
      var self = this;
      if (!C.chooseSheet) return;
      C.chooseSheet(it.name, it.options.map(function (o) { return { name: o.name, key: o.playlist, icon: it.icon }; }), function (opt) {
        self._playList({ playlist: opt.key, name: opt.name }, el);
      });
    };
    // CHOOSE A PLAYLIST (the block's When Tapped, 2026-11-01, the owner: "1 quick button to launch any playlist", "more
    // like a detail sheet... similar to how the playlists look on the large or x-large card, but in a pop up"): every
    // playlist as the block's covers, in a detail sheet (hk-music-playlists-card, below); the plain pick-one list only
    // where there is no detail sheet
    HkRecentMusicCard.prototype._choosePlaylist = function () {
      var Mu = window.hkMusic, tiles = playlistTiles(Mu && Mu.playlists ? Mu.playlists() : [], null), self = this, D = window.hkDetail;
      var el = this._root.querySelector('hk-plate') || this;
      if (!tiles.length) {
        window.hkShell.toast({ message: 'No playlists yet. Add some in ' + window.hkShell.settingsPlace('Pages → Music') + '.' }, this);
        return;
      }
      var sp = this._config && this._config.speaker;
      if (D && D.open && customElements.get('hk-music-playlists-card')) {
        D.open(null, { name: 'Playlists', icon: 'mdi:playlist-music' },
          { cards: { cards: [Object.assign({ type: 'custom:hk-music-playlists-card' }, sp ? { speaker: sp } : {})], width: 'wide' } });
        return;
      }
      if (!C.chooseSheet) return;
      C.chooseSheet('Play a Playlist', tiles.map(function (t, i) { return { name: t.name, key: String(i), icon: t.icon }; }), function (opt) {
        var t = tiles[+opt.key];
        if (t) self._play(t, el);
      });
    };
    register('hk-recent-music-card', HkRecentMusicCard, 'HK Recently Played',
      'What played last and covers to play again, sized to a Home Grid block.', null, function () { return {}; });
    // (the Home Grid's Music block's: not offered in the card picker)
    if (C.unlisted) C.unlisted('hk-recent-music-card');
    register('hk-music-playlists-card', HkMusicPlaylistsCard, 'HK Playlists',
      'Every playlist as covers, to play one where the Music block plays.', null, function () { return {}; });
    if (C.unlisted) C.unlisted('hk-music-playlists-card');
    register('hk-tv-channels-card', HkTvChannelsCard, 'HK Live TV Channels',
      'The Live TV page\'s first channels with what is on, sized to a Home Grid block; a tap plays one full screen.', null, function () { return {}; });
    // (the Home Grid's Live TV block's: not offered in the card picker)
    if (C.unlisted) C.unlisted('hk-tv-channels-card');

    // (for tests: the Home Grid widgets' pure pieces)
    window.hkMedia = { version: '1.0.0', _: { recentCovers: recentCovers, playlistTiles: playlistTiles, tvGrid: tvGrid, tintOf: tintOf, RECENT: RECENT, TV_SLOTS: TV_SLOTS } };
  });
  });
})();
