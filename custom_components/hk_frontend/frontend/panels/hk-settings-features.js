// hk-settings-features.js -- THE FEATURES' OWN SETTINGS on the HK Settings
// page.
//
// Each page belongs to one of HK Frontend's optional features -- Music, Live
// TV, Alarm PIN, Clean Areas -- each an ITEM of the integration's one entry,
// added from Settings -> Devices & services -> HK Frontend -> Add feature
// (features/__init__.py). A page reads and saves through that feature's own
// commands (`<id>/settings/get` and `/set`, e.g. hk_tv/settings/get), which
// check each change the way the feature's gear does and store it where the
// gear stores it -- in the feature's item. panel/get `features` lists each
// feature with its items; not yet added, its page offers Add.
// Every choice comes from the house as it is -- the tuner's lineup, the
// vacuums, the alarm panels, Music Assistant's players -- never from a list
// written here.
//
// The page (hk-settings.js) owns drawing and saving; this file is the pages'
// content, and the pure parts are tested in tests/test_features.js.
(function () {
  'use strict';
  var root = typeof window !== 'undefined' ? window : globalThis;
  // the product's name, and Home Assistant's own places, as the host says
  // them (web/client/hk-host-shell.js): HK Frontend in HA, the host's own elsewhere
  function PN() { return root.hkShell.productName(); }
  function haPlace(path) { return root.hkShell.haPlace(path); }
  if (root.hkSettingsFeatures) return;

  // ------------------------------------------------------------ the parts (generated by tools/split_js.py)
  // THIS FILE IS THE SHELL. Its members are cut into the files of web/hk/settings-features/ (the PARTS below, in the order they
  // run) by tools/split_js.py from tools/split_manifests/settings-features.json; `split_js.py --find <name>` says which file holds
  // one. Each file registers one function in window.hkSettingsFeaturesParts; they run here, in this order (a later one may use
  // an earlier one), each given the kit K: what the parts use of the shell, in one object. What the shell uses of them,
  // they hand back on K, and it is taken from there. The files are fetched in parallel; a host that has already loaded
  // them (the suites) starts at once, in the same turn.
  // READY: window.__hkSplitReady['hk-settings-features'] is a promise that resolves once the parts have run (and rejects if they
  // never come), so a page that imports this file and uses it at once awaits it first (web/home.js imp, hk-loader).
  var PARTS = ['hk-settings-features-pure.js', 'hk-settings-features-devices.js', 'hk-settings-features-energy.js',
               'hk-settings-features-notify.js'];
  var PARTS_TRIES = 6;
  function partKey(file) { return file.replace(/\.js$/, ''); }
  function partsSettle(err) {
    var settle = (window.__hkSplitSettle || {})['hk-settings-features'];
    if (settle) settle(err);
  }
  // ONE FILE THAT DIDN'T COME (a tablet's Wi-Fi waking, the server restarting) used to leave the cards dead until a reload
  // (the third audit pass, WEB-11): the ones still missing are asked for again, a little later each time, at an address
  // of their own -- a browser keeps a failed module's answer for its address
  function loadParts(then, n) {
    // (the first call has no n; the retries and the finish pass it) a shell evaluated twice before its parts arrive
    // must not run them twice: the flag is set at once, not when the parts have run
    var started = window.__hkSplitStarted = window.__hkSplitStarted || {};
    if (n === undefined) {
      if (started['hk-settings-features']) return;
      started['hk-settings-features'] = true;
      var ready = new Promise(function (resolve, reject) {
        (window.__hkSplitSettle = window.__hkSplitSettle || {})['hk-settings-features'] = function (err) { if (err) reject(err); else resolve(); };
      });
      ready.catch(function () { /* the console says so; an importer that awaits it reports it */ });
      (window.__hkSplitReady = window.__hkSplitReady || {})['hk-settings-features'] = ready;
    }
    n = n || 0;
    var have = window.hkSettingsFeaturesParts || {};
    var missing = PARTS.filter(function (file) { return !have[partKey(file)]; });
    if (!missing.length) {
      var failed = null;
      try { then(); } catch (err) { failed = err; console.error('[hk-settings-features] the parts did not start', err); }
      // (the checks that drive a page wait for every shell that started to say it is done)
      (window.__hkSplitDone = window.__hkSplitDone || {})['hk-settings-features'] = true;
      partsSettle(failed);
      return;
    }
    // (window.hkV: the build's ?v= on an address put together here, web/shim/base.js)
    Promise.all(missing.map(function (file) {
      var u = '/hk/settings-features/' + file, href = window.hkV ? window.hkV(u) : u;
      var got = n ? import(href + (href.indexOf('?') < 0 ? '?' : '&') + 'retry=' + n) : import(href);
      return got.catch(function (err) { return err; });
    })).then(function (got) {
      var err = got.filter(function (r) { return r instanceof Error; })[0];
      var left = PARTS.filter(function (file) { return !(window.hkSettingsFeaturesParts || {})[partKey(file)]; });
      if (!left.length) { loadParts(then, n); return; }
      err = err || new Error(left[0] + ' ran without registering');
      if (n + 1 >= PARTS_TRIES) {
        console.error('[hk-settings-features] the parts did not start', err);
        partsSettle(err);
        // (given up: a later import of this file -- a page asking again at an address of its own -- starts over)
        delete started['hk-settings-features'];
        return;
      }
      console.warn('[hk-settings-features] a part did not load (' + err.message + '); again shortly');
      setTimeout(function () { loadParts(then, n + 1); }, Math.min(1000 * Math.pow(2, n), 15000));
    });
  }
  // ------------------------------------------------------------ end of the parts loader
  var addHref, batteriesStored, cooldownLabel, dndRows, dndSummary, energyFound, integrationHref, LIST, listed,
      musicTop, notifySummary, own, page, pairChoices, pairNote, pairsAfter, playlistSub, roomCount, roomLists, SCOPE,
      search, sectionsAfter, setFeature, speakerLists, speakerName, stateOf, stayLabel, trigWord, tvCount, tvLists,
      vacuumsAfter, vacuumSub, wakesOf, whenControl;

  // ----------------------------------------------------------------- pages
  var K = null;
  function use(kit) { K = kit; bindLate(); }

  var WHAT = {
    hk_tv: 'Live TV isn’t added yet. It plays an HDHomeRun tuner’s channels on your screens, with a guide.',
    hk_alarm_pin: 'Alarm PIN isn’t added yet. It puts a PIN in front of an alarm panel.',
    hk_clean_areas: 'Clean Areas isn’t added yet. It sends each vacuum the chosen rooms on its own map.',
    hk_energy: 'Energy isn’t added yet. It builds an Energy page — whole-home power, today’s cost, daily use and a live tile per circuit — from Home Assistant’s Energy settings.',
    hk_music: 'Music isn’t added yet. It plays music in chosen rooms through Music Assistant.',
    hk_notify:
      'Notifications isn’t added yet. It shows a banner at the top of your screens when an accessory does something — a door opens, someone arrives, a camera sees a person — with a camera’s snapshot.'
  };

  // ADVANCED -> FEATURES: every feature on one page, a switch each, what it
  // needs, and the page that holds its settings. The same switch as the
  // feature page's Add and Remove (`<id>/feature/set`). A host whose
  // features are Home Assistant's (HK Frontend) lists them with the way to
  // add one there instead.
  var NEEDS = {
    hk_music: 'Needs Music Assistant', hk_tv: 'Needs an HDHomeRun tuner', hk_alarm_pin: 'Needs an alarm panel',
    hk_clean_areas: 'Needs a vacuum with room maps', hk_energy: 'Needs Home Assistant’s Energy settings, or devices that report power',
    hk_notify: 'Needs nothing more: you choose what it tells'
  };
  var SETTINGS_AT = { hk_music: '#/page/music', hk_tv: '#/page/live_tv', hk_alarm_pin: '#/page/security',
                      hk_clean_areas: '#/page/vacuums', hk_energy: '#/page/energy', hk_notify: '#/features/notify' };
  // FEATURES ON BY DEFAULT (a host whose features are its own): under a feature the host turned on by itself,
  // when and why, in place of what it needs; under one that's off but near, what's still missing
  function hostName() {
    try { return PN() || 'the host'; } catch (e) { return 'the host'; }
  }
  function shortDate(at) {
    var d = new Date(at);
    return isNaN(d.getTime()) ? '' : d.toLocaleDateString('en-US', { month: 'short', day: 'numeric' });
  }
  function featureSub(f, d) {
    if (f && f.auto && f.auto.why) {
      var when = shortDate(f.auto.at);
      return 'Turned on by ' + hostName() + (when ? ' on ' + when : '') + ': ' + f.auto.why;
    }
    if (f && f.note) return f.note;
    return NEEDS[d];
  }
  // the switch, only where the host holds the features itself (panel/get's `features_auto`, with its save type)
  function autoGroup(P, c) {
    var a = P.data.features_auto;
    if (!a || typeof a.enabled !== 'boolean' || typeof a.save !== 'string') return;
    c.appendChild(K.group({ footer: 'When the house has what a feature needs — Music Assistant connected, a vacuum with room maps, Home Assistant’s Energy settings, a tuner that answers — ' +
      hostName() + ' turns it on once and tells you. A feature you turn off stays off.' }, [
      K.toggle({ label: 'Turn Features On Automatically', icon: 'mdi:auto-fix', on: a.enabled, fk: 'features:auto',
                 onChange: function (v) {
                   return P.ws({ type: a.save, enabled: v }).then(function (ok) {
                     if (!ok) return;
                     return P.reload().then(function () { P.render(true); });
                   });
                 } })]));
  }
  function featureList(P, c) {
    var feats = P.data.features || {};
    var rows = LIST.filter(function (x) { return stateOf(feats, x[1]) !== 'missing'; });
    if (!rows.length) { c.appendChild(K.group({ footer: 'No features are reported yet. They show once Home Assistant is connected.' }, [])); return; }
    var mine = rows.some(function (x) { return own(P, x[1]); });
    if (mine) autoGroup(P, c);
    c.appendChild(K.group({ footer: mine
        ? 'On: the feature’s page and its settings come to every screen. Off: it leaves every screen, and its settings are kept for turning it on again. Each feature’s own page has the same switch.'
        : 'Each feature is added in ' + haPlace('Devices & Services → HK Frontend → Add feature') + '.' },
      rows.map(function (x) {
        var d = x[1], on = stateOf(feats, d) === 'added', name = (feats[d] || {}).name || x[2];
        if (!own(P, d)) {
          return K.nav({ label: name, sub: NEEDS[d], value: on ? 'Added' : 'Not Added', icon: x[3], href: on ? SETTINGS_AT[d] : addHref(d), fk: 'features:' + d });
        }
        return K.toggle({ label: name, sub: featureSub(feats[d], d), icon: x[3], on: on, fk: 'features:switch:' + d,
                          onChange: function (v) { setFeature(P, d, v); } });
      })));
    var on = rows.filter(function (x) { return stateOf(feats, x[1]) === 'added'; });
    if (on.length) c.appendChild(K.group({ header: 'Settings' }, on.map(function (x) {
      return K.nav({ label: (feats[x[1]] || {}).name || x[2], icon: x[3], href: SETTINGS_AT[x[1]], fk: 'features:open:' + x[1] });
    })));
  }
  function featuresOn(features) {
    var rows = listed(features).filter(function (x) { return stateOf(features, x[1]) !== 'missing'; });
    return { on: rows.filter(function (x) { return stateOf(features, x[1]) === 'added'; }).length, of: rows.length };
  }

  // THE SHELL'S VARIABLES SET ONCE, LATER (K): each part that uses one has its own copy, handed over here
  // whenever the shell has assigned them (the parts run, and the page's start)
  var lates = [];
  function bindLate() {
    var s = { K: K };
    lates.forEach(function (bind) { bind(s); });
  }
  function kit() {
    return {
      haPlace: haPlace, PN: PN, WHAT: WHAT, late: lates
    };
  }
  function runParts() {
    var KIT = kit();
    PARTS.forEach(function (file) { window.hkSettingsFeaturesParts[partKey(file)](KIT); });
    addHref = KIT.addHref; batteriesStored = KIT.batteriesStored; cooldownLabel = KIT.cooldownLabel;
    dndRows = KIT.dndRows; dndSummary = KIT.dndSummary; energyFound = KIT.energyFound;
    integrationHref = KIT.integrationHref; LIST = KIT.LIST; listed = KIT.listed; musicTop = KIT.musicTop;
    notifySummary = KIT.notifySummary; own = KIT.own; page = KIT.page; pairChoices = KIT.pairChoices;
    pairNote = KIT.pairNote; pairsAfter = KIT.pairsAfter; playlistSub = KIT.playlistSub; roomCount = KIT.roomCount;
    roomLists = KIT.roomLists; SCOPE = KIT.SCOPE; search = KIT.search; sectionsAfter = KIT.sectionsAfter;
    setFeature = KIT.setFeature; speakerLists = KIT.speakerLists; speakerName = KIT.speakerName;
    stateOf = KIT.stateOf; stayLabel = KIT.stayLabel; trigWord = KIT.trigWord; tvCount = KIT.tvCount;
    tvLists = KIT.tvLists; vacuumsAfter = KIT.vacuumsAfter; vacuumSub = KIT.vacuumSub; wakesOf = KIT.wakesOf;
    whenControl = KIT.whenControl;
    bindLate();
  }

  loadParts(function () {
    runParts();

    root.hkSettingsFeatures = {
      LIST: LIST, listed: listed, stateOf: stateOf, page: page, use: use, addHref: addHref, search: search, musicTop: musicTop,
      integrationHref: integrationHref, SCOPE: SCOPE, WHAT: WHAT, dndRows: dndRows, dndSummary: dndSummary,
      featureList: featureList, featuresOn: featuresOn, featureSub: featureSub, NEEDS: NEEDS, SETTINGS_AT: SETTINGS_AT,
      _: { tvLists: tvLists, tvCount: tvCount, speakerLists: speakerLists, speakerName: speakerName, pairNote: pairNote, pairChoices: pairChoices, pairsAfter: pairsAfter, playlistSub: playlistSub,
        vacuumSub: vacuumSub, vacuumsAfter: vacuumsAfter,
           roomLists: roomLists, roomCount: roomCount, energyFound: energyFound, sectionsAfter: sectionsAfter,
           batteriesStored: batteriesStored, stayLabel: stayLabel, notifySummary: notifySummary, whenControl: whenControl,
           cooldownLabel: cooldownLabel, wakesOf: wakesOf, trigWord: trigWord }
    };
  });
})();
